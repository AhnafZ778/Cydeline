import type { Role } from "../../lib/socLogic";

export type AlertType = "Exchange" | "Proxy" | "Malware" | "Web Attack" | "Unauthorized Access";
export type Severity = "Critical" | "High" | "Medium" | "Low";

export type PracticeAlert = {
  id: string;
  eventId: string;
  rule: string;
  severity: Severity;
  type: AlertType;
  when: string;
  role: Role;
  startsClosed?: boolean;
  playbook: string;
  level: string;
  hostId: string;
  fields: { label: string; value: string }[];
  writeup: string;
  summary: string;
  links: { label: string; href: string }[];
};

function row(
  partial: Omit<PracticeAlert, "level" | "links"> & { level?: string; links?: PracticeAlert["links"] },
): PracticeAlert {
  return { level: "Security Analyst", links: [], ...partial };
}

